# What Is Inheritance?

# Imagine a family.

# Suppose your father has:

# Two eyes
# Two ears
# A nose
# The ability to walk

# You inherit many of these characteristics.

# You don't have to recreate them from scratch.

# Inheritance in Python works similarly.

# A child class can inherit attributes and methods from a parent class.

# Instead of rewriting code, you reuse existing code.

#             Person
#                |
#     ---------------------
#     |         |         |
#  Student   Teacher   Doctor


# All of them are people.

# Therefore:

# name
# age
# walk()
# eat()

# can live in Person.

# The child classes inherit them automatically.