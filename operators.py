# Operators are symbols that tell Python to perform an operation.

age = 24
years_to_thirty = 30 - age
print(years_to_thirty)

# addition
a = 10
b = 5
print(a + b)

# Subtraction (-)
print(a - b)

# Multiplication (*)
print (a * b)

# Division (/)
print (a / b)

# Floor Division (//)
print(a // b)

# Modulus (%)
print(a % b)


# Exponent (**)
print(a ** b)